fn glyph(c: char) -> u16 {
    let c = c.to_ascii_uppercase();
    for (g, s) in GLYPHS {
        if *g == c {
            let mut bits = 0u16;
            for (i, ch) in s.chars().filter(|c| *c != '/').enumerate() {
                if ch == '#' {
                    bits |= 1 << i;
                }
            }
            return bits;
        }
    }
    0b111_101_101_101_111 // box for unknown glyphs
}

pub fn text_width(s: &str) -> i32 {
    let n = s.chars().count() as i32;
    if n == 0 {
        0
    } else {
        n * 4 - 1
    }
}

/// Draw `s` with its top-left at (x, y). `put` receives (x, y) of each lit pixel.
pub fn draw(s: &str, x: i32, y: i32, mut put: impl FnMut(i32, i32)) {
    let mut cx = x;
    for c in s.chars() {
        let g = glyph(c);
        for i in 0..15 {
            if g & (1 << i) != 0 {
                put(cx + (i % 3) as i32, y + (i / 3) as i32);
            }
        }
        cx += 4;
    }
}

/// Shorten a filename so a tag stays a sensible width.
pub fn label_for(name: &str, max: usize) -> String {
    let clean: String = name
        .chars()
        .map(|c| if c.is_ascii() { c } else { '?' })
        .collect();
    if clean.chars().count() <= max {
        return clean;
    }
    let keep = max.saturating_sub(2);
    let head: String = clean.chars().take(keep).collect();
    format!("{head}..")
}
